insert into public.attendance (worker_id, work_date, item_id, check_in, check_out, price_applied, source, note)
select w.id, (date '2026-11-01' + s.d), i.id,
       ((date '2026-11-01' + s.d)::timestamp + time '09:00') at time zone 'Asia/Seoul',
       ((date '2026-11-01' + s.d)::timestamp + time '18:00') at time zone 'Asia/Seoul',
       public.price_on(i.id, date '2026-11-01' + s.d), 'admin', '엑셀 이관(날짜 미정)'
from src s
join public.workers w on w.phone = s.phone
join public.items i on i.name = s.item
on conflict (worker_id, work_date, item_id) do nothing;

